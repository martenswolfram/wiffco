# Sigmoid Symmetric Transfer Function
def tansig_apply(n):
    a = 2 / (1 + np.exp(-2 * n)) - 1
    return a

# Map Minimum and Maximum Output Reverse-Processing Function
def mapminmax_reverse(y, settings):
    x = y - settings['ymin']
    x = x / settings['gain']
    x = x + settings['xoffset']
    return x

